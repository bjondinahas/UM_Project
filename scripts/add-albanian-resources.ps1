function Repair-SqResx($path) {
    $lines = Get-Content $path -Encoding UTF8
    $out = New-Object System.Collections.Generic.List[string]
    foreach ($line in $lines) {
        if ($line -match '^<data name="(Common_Unknown|Status_|Modal_|Table_|Search_|Page_|Msg_|Default_|Form_|Cal_)') { continue }
        if ($line -match '^</root>' -and $out[$out.Count-1] -match '^<data name="(Common_Unknown|Status_|Modal_|Table_|Search_|Page_|Msg_|Default_|Form_|Cal_)') { continue }
        $out.Add($line)
    }
    # Remove trailing duplicate blank before root
    while ($out.Count -gt 0 -and $out[$out.Count-1].Trim() -eq '' -and $out[$out.Count-1] -notmatch '</root>') { $out.RemoveAt($out.Count-1) }
    if ($out[$out.Count-1] -notmatch '</root>') {
        # ensure ends with </root>
    }
    $utf8Bom = New-Object System.Text.UTF8Encoding $true
    [System.IO.File]::WriteAllLines($path, $out, $utf8Bom)
}

function Add-Keys($path) {
    $xml = Get-Content $path -Raw -Encoding UTF8
    if ($xml -notmatch '</root>') { throw "Invalid resx: $path" }
    $existing = @()
    foreach ($m in [regex]::Matches($xml, 'name="([^"]+)"')) { $existing += $m.Groups[1].Value }
    $toAdd = @()
    foreach ($line in $keys -split "`n") {
        if ($line -match 'name="([^"]+)"') {
            $n = $Matches[1]
            if ($existing -notcontains $n) { $toAdd += $line.Trim() }
        }
    }
    if ($toAdd.Count -eq 0) { Write-Host "No new keys for $path"; return }
    $insert = "`n" + ($toAdd -join "`n") + "`n"
    $xml = $xml -replace '</root>', ($insert + '</root>')
    $utf8Bom = New-Object System.Text.UTF8Encoding $true
    $settings = New-Object System.Xml.XmlWriterSettings
    $settings.Encoding = $utf8Bom
    $settings.Indent = $true
    $settings.IndentChars = '  '
    $writer = [System.Xml.XmlWriter]::Create($path, $settings)
    $xmlDoc = [xml]$xml
    $xmlDoc.Save($writer)
    $writer.Close()
    Write-Host "Added $($toAdd.Count) keys to $path"
}

