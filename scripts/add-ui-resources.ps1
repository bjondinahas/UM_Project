function Add-Keys($path) {
    $utf8Bom = New-Object System.Text.UTF8Encoding $true
    $xml = [xml]([System.IO.File]::ReadAllText($path, $utf8Bom))
    $existing = @{}
    foreach ($d in $xml.root.data) { if ($d.name) { $existing[$d.name] = $true } }
    $toAdd = @()
    foreach ($line in $keys -split "`n") {
        if ($line -match 'name="([^"]+)"' -and $line -match '<value>(.*)</value>') {
            $n = $Matches[1]
            if (-not $existing.ContainsKey($n)) {
                $toAdd += "  $line"
            } else {
                if ($line -match '<value>(.*)</value>') {
                    $node = $xml.root.data | Where-Object { $_.name -eq $n } | Select-Object -First 1
                    if ($node) { $node.value = $Matches[1] }
                }
            }
        }
    }
    if ($toAdd.Count -gt 0) {
        $insert = ($toAdd -join "`n") + "`n"
        $raw = [IO.File]::ReadAllText($path, $utf8Bom)
        $raw = $raw -replace '</root>', ($insert + '</root>')
        $xml = [xml]$raw
    }
    $settings = New-Object System.Xml.XmlWriterSettings
    $settings.Encoding = $utf8Bom
    $settings.Indent = $true
    $settings.IndentChars = '  '
    $w = [System.Xml.XmlWriter]::Create($path, $settings)
    $xml.Save($w)
    $w.Close()
    Write-Host "Updated $([IO.Path]::GetFileName($path)) (+$($toAdd.Count) new)"
}

